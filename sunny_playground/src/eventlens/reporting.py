"""Write analysis outputs as CSV plus a readable Markdown summary."""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd


def markdown_table(frame: pd.DataFrame, digits: int = 4) -> str:
    """Render a DataFrame as a GitHub Markdown table without extra dependencies."""
    if frame.empty:
        return "_(no rows)_"
    formatted = frame.copy()
    for column in formatted.columns:
        formatted[column] = formatted[column].map(lambda value: _format(value, digits))
    header = "| " + " | ".join(map(str, formatted.columns)) + " |"
    divider = "|" + "|".join("---" for _ in formatted.columns) + "|"
    rows = ["| " + " | ".join(row) + " |" for row in formatted.astype(str).to_numpy()]
    return "\n".join([header, divider, *rows])


def _format(value, digits: int) -> str:
    if isinstance(value, (bool, np.bool_)):
        return "yes" if value else "no"
    if isinstance(value, (float, np.floating)):
        if np.isnan(value):
            return ""
        return f"{value:.{digits}g}" if abs(value) < 1e-3 and value != 0 else f"{value:.{digits}f}".rstrip("0").rstrip(".")
    if isinstance(value, pd.Timestamp):
        return value.strftime("%Y-%m-%d")
    return str(value)


class ReportWriter:
    """Collects sections and writes `<name>.csv` files plus one Markdown file."""

    def __init__(self, directory: Path, title: str):
        self.directory = directory
        self.directory.mkdir(parents=True, exist_ok=True)
        self.lines = [f"# {title}", "", "Generated by `scripts/run_research.py`. Do not edit by hand.", ""]

    def section(self, heading: str, text: str = "") -> None:
        self.lines += [f"## {heading}", ""]
        if text:
            self.lines += [text, ""]

    def table(self, name: str, frame: pd.DataFrame, caption: str = "") -> None:
        frame.to_csv(self.directory / f"{name}.csv", index=False)
        if caption:
            self.lines += [f"**{caption}** (`{name}.csv`)", ""]
        self.lines += [markdown_table(frame), ""]

    def facts(self, values: dict) -> None:
        frame = pd.DataFrame({"metric": list(values), "value": list(values.values())})
        self.lines += [markdown_table(frame), ""]

    def write(self, filename: str = "results.md") -> Path:
        path = self.directory / filename
        path.write_text("\n".join(self.lines), encoding="utf-8")
        return path
